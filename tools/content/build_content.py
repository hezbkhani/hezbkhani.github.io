def norm(s):
    s = plain(s).replace('ي', 'ی').replace('ى', 'ی').replace('ك', 'ک').replace('ۚ', '').replace('ۖ', '').replace('ۗ', '').replace('ۛ', '')
    return re.sub(r'\s+', ' ', s)

out = []
for title, items in DUAS:
    group = []
    for s, a, b, t, who, key in items:
        ar = [V[(s, n)][0] for n in range(a, b + 1)]
        fa = [V[(s, n)][1] for n in range(a, b + 1)]
        joined = norm(' '.join(ar))
        k = norm(key)
        if k not in joined:
            raise SystemExit(f'{s}:{a}-{b} {t}: «{key}» در متن نیست:\n{joined[:300]}')
        group.append({'s': s, 'a': a, 'b': b, 't': t, 'who': who, 'ar': ar, 'fa': fa})
    out.append({'title': title, 'items': group})

